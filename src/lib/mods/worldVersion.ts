/**
 * World compatibility for modpack Minecraft-version swaps. A world generated
 * by release X carries level.dat in X's format; a pack targeting an OLDER
 * release can't parse it (seen live on v0.5.13: a server that booted vanilla
 * 26.2 once, then got ATM10 installed — level.dat written by 26.2 has no
 * WorldGenSettings, and 1.21.1 refuses it with "Failed to load datapacks,
 * can't proceed with server load" before FML exits 0 — so the boot test
 * failed and the whole pack install rolled back, every time). During a
 * version swap the existing world must move aside so the pack's release
 * generates a fresh, compatible one.
 */

import fs from "fs";
import path from "path";
import zlib from "zlib";
import { safeJoin } from "@/lib/safePath";

export interface LevelDataVersion {
  /** level.dat exists — there is a world to worry about. */
  exists: boolean;
  /** The Data.DataVersion int from level.dat; null when unparseable. */
  dataVersion: number | null;
}

/**
 * The level directory a server boots: server.properties' level-name, else
 * Minecraft's default "world".
 */
export function levelNameFor(serverRoot: string): string {
  try {
    const props = fs.readFileSync(path.join(serverRoot, "server.properties"), "utf8");
    const m = /^level-name=(.*)$/m.exec(props);
    if (m && m[1].trim()) return m[1].trim();
  } catch {
    /* no server.properties — default */
  }
  return "world";
}

/**
 * Read the world's DataVersion straight out of the gzipped NBT level.dat —
 * no NBT dependency, just the one named TAG_Int we need: tag byte 0x03,
 * big-endian name length 0x000B, the ASCII name, then the big-endian value.
 */
export function readLevelDataVersion(serverRoot: string, levelName: string): LevelDataVersion {
  let raw: Buffer;
  try {
    raw = fs.readFileSync(safeJoin(serverRoot, levelName, "level.dat"));
  } catch {
    return { exists: false, dataVersion: null };
  }
  try {
    const nbt = zlib.gunzipSync(raw);
    const name = Buffer.from("DataVersion", "latin1");
    for (let i = 0; i + 3 + name.length + 4 <= nbt.length; i++) {
      if (nbt[i] !== 0x03 || nbt[i + 1] !== 0x00 || nbt[i + 2] !== name.length) continue;
      if (!name.equals(nbt.subarray(i + 3, i + 3 + name.length))) continue;
      return { exists: true, dataVersion: nbt.readInt32BE(i + 3 + name.length) };
    }
  } catch {
    /* fall through: corrupt gzip or unreadable NBT */
  }
  return { exists: true, dataVersion: null };
}

export interface WorldStashResult {
  /** Directory the world was moved to; absent when nothing moved. */
  movedTo?: string;
  fromDataVersion?: number | null;
  reason?: string;
}

/**
 * Move the existing world aside when the pack's Minecraft release can't load
 * it: on a downgrade (world DataVersion above the target release's), when
 * either DataVersion is unknown, or when level.dat exists but can't be
 * parsed at all. Upgrades load their world fine, so nothing moves there.
 * The world is renamed (never deleted) so the user can restore it; a fresh
 * world generates under the old name on next boot. Returns the stash
 * location; empty result = the world stayed.
 */
export function stashWorldForMcSwitch(args: {
  serverRoot: string;
  to: string;
  targetDataVersion: number | null;
  levelName?: string;
}): WorldStashResult {
  const levelName = args.levelName ?? levelNameFor(args.serverRoot);
  const level = readLevelDataVersion(args.serverRoot, levelName);
  if (!level.exists) return {};
  if (
    level.dataVersion !== null &&
    args.targetDataVersion !== null &&
    level.dataVersion <= args.targetDataVersion
  ) {
    return {}; // the target release can read this world — leave it alone
  }

  const from = safeJoin(args.serverRoot, levelName);
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  let movedTo = safeJoin(args.serverRoot, `${levelName}.pre-mc-${args.to}-${stamp}`);
  let n = 2;
  while (fs.existsSync(movedTo)) {
    movedTo = safeJoin(args.serverRoot, `${levelName}.pre-mc-${args.to}-${stamp}-${n++}`);
  }
  try {
    fs.renameSync(from, movedTo);
  } catch (err: any) {
    throw new Error(
      `This pack targets Minecraft ${args.to}, but the existing world can't load under it and moving '${levelName}/' aside failed: ${err.message}. Make sure the server is fully stopped, then reinstall.`
    );
  }
  return {
    movedTo,
    fromDataVersion: level.dataVersion,
    reason:
      level.dataVersion === null
        ? "its level.dat couldn't be parsed"
        : args.targetDataVersion === null
          ? "the target release's DataVersion is unknown"
          : `it was generated by a newer Minecraft (DataVersion ${level.dataVersion} > ${args.targetDataVersion})`,
  };
}
