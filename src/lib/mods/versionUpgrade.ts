/**
 * In-place Minecraft version switch for an existing server — the flow
 * modpack installs get for free through their pinned `mcSwitch`, exposed
 * directly: pick a release, snapshot, stash an incompatible world aside,
 * swap server.jar, reinstall the loader for the new release, boot-test in
 * the sandbox, roll back on any failure. Works for vanilla and loader
 * servers alike; local runners only (a version swap needs the server's
 * files plus a sandbox boot, which remote nodes don't have yet).
 */

import path from "path";
import { dataRoot } from "@/lib/appPaths";
import { prisma } from "@/lib/db";
import { createSnapshot, restoreSnapshot, discardSnapshot } from "@/lib/snapshots";
import {
  applyVanillaServerSwap,
  resolveVanillaServerJar,
  type VanillaServerJar,
} from "./mcServerJar";
import {
  detectMinecraftVersion,
  installFabricServer,
  installForgeServer,
  installNeoForgeServer,
  installQuiltServer,
  readLoaderMarker,
  type LoaderMarker,
} from "./mcLoaders";
import {
  beginProgress,
  createBootLogEmitter,
  emitProgress,
  endProgress,
} from "./progress";
import { testServerBootWithQuarantine } from "./bootRetry";
import { stashWorldForMcSwitch } from "./worldVersion";

const LOADER_LABELS: Record<string, string> = {
  fabric: "Fabric",
  quilt: "Quilt",
  forge: "Forge",
  neoforge: "NeoForge",
};

/** Preflight failure (unknown release, nothing installed yet, already on
 *  the target) — nothing on disk was touched, so the route maps this to 400. */
export class VersionUpgradeError extends Error {}

export interface VersionUpgradeResult {
  message: string;
  warnings: string[];
}

export async function upgradeMinecraftVersion(args: {
  serverId: string;
  userId: string;
  serverName: string;
  targetVersion: string;
  installId?: string;
}): Promise<VersionUpgradeResult> {
  const { serverId, userId, serverName, targetVersion, installId } = args;
  const serverRoot = path.join(dataRoot(), "local-servers", serverId);
  const warnings: string[] = [];
  const p = (event: Parameters<typeof emitProgress>[1]) => {
    if (installId) emitProgress(installId, event);
  };

  // Preflight — 400-class: costs nothing, touches nothing.
  let from: string;
  let loader: LoaderMarker | null;
  let jar: VanillaServerJar;
  try {
    const detected = detectMinecraftVersion(serverRoot);
    if (!detected) {
      throw new VersionUpgradeError(
        "No server.jar found — start this server once first so its files exist."
      );
    }
    from = detected;
    if (from === targetVersion) {
      throw new VersionUpgradeError(`This server is already running Minecraft ${from}.`);
    }
    loader = readLoaderMarker(serverRoot);
    jar = await resolveVanillaServerJar(targetVersion);
  } catch (err: any) {
    if (err instanceof VersionUpgradeError) throw err;
    throw new VersionUpgradeError(err?.message || "Couldn't plan the version switch.");
  }

  if (installId) beginProgress(installId);
  p({ stage: "snapshot", label: "Taking a safety snapshot" });

  try {
    const snapshot = await createSnapshot(
      serverId,
      userId,
      `Pre-upgrade: Minecraft ${from} → ${targetVersion}`
    );

    try {
      // A world generated by a newer release can't load under the target
      // (and unknown/unparseable level.dat is treated the same) — move it
      // aside so the boot test generates a fresh, compatible world instead
      // of failing and rolling the whole switch back. Upgrades keep theirs.
      const stash = stashWorldForMcSwitch({
        serverRoot,
        to: targetVersion,
        targetDataVersion: jar.dataVersion ?? null,
      });
      if (stash.movedTo) {
        warnings.push(
          `Moved the existing world to '${path.basename(stash.movedTo)}' — ${stash.reason}; ` +
            `Minecraft ${targetVersion} will generate a fresh one. Delete the stash folder when you're sure you don't need it.`
        );
        p({ stage: "mcswap", label: "Moving the old version's world aside", current: 0, total: 1 });
        p({ current: 1 });
      }

      p({ stage: "mcswap", label: `Switching server.jar to Minecraft ${targetVersion}`, current: 0, total: 1 });
      console.log(`[VersionUpgrade ${serverId}] server.jar: Minecraft ${from} → ${targetVersion}`);
      await applyVanillaServerSwap({ serverRoot, jar });
      p({ current: 1 });

      // A loader's libraries target the release it was installed for —
      // after a switch, reinstall the same loader type for the new one.
      // (Modpack installs do exactly this when their pack bumps the MC
      // version; see applyModpackPlan's packLoader branch.)
      if (loader) {
        const label = LOADER_LABELS[loader.type] ?? loader.type;
        p({ stage: "loader", label: `Installing ${label} for Minecraft ${targetVersion}`, current: 0, total: 1 });
        const onLog = (msg: string) => {
          console.log(`[VersionUpgrade ${serverId}] ${msg}`);
          p({ label: msg });
        };
        if (loader.type === "fabric") {
          await installFabricServer(serverRoot, targetVersion, onLog);
        } else if (loader.type === "quilt") {
          await installQuiltServer(serverRoot, targetVersion, { onLog });
        } else if (loader.type === "forge") {
          await installForgeServer(serverRoot, targetVersion, { onLog });
        } else {
          await installNeoForgeServer(serverRoot, targetVersion, { onLog });
        }
        p({ current: 1 });
      }

      p({ stage: "boot", label: "Booting the server once to verify the switch", current: 0, total: 1 });
      const bootLog = createBootLogEmitter(installId);
      const quarantined = await testServerBootWithQuarantine({
        serverId,
        serverRoot,
        game: "MINECRAFT",
        warnings,
        onProgress: (lbl) => p({ label: lbl }),
        onBootLine: bootLog,
      });
      // Quarantined jars' install rows are keyed by jar basename.
      for (const name of quarantined) {
        await prisma.modInstallation.deleteMany({
          where: { serverId, packageId: name.replace(/\.jar$/, "") },
        });
      }
      p({ current: 1 });

      const loaderNote = loader ? ` with ${LOADER_LABELS[loader.type] ?? loader.type} reinstalled for it` : "";
      await prisma.activityLog.create({
        data: {
          userId,
          action: "UPDATE_SERVER",
          details: `Switched Minecraft ${from} → ${targetVersion} on server '${serverName}'${loaderNote}.`,
        },
      });

      if (installId) endProgress(installId, "done");
      return {
        message: `This server now runs Minecraft ${targetVersion}${loaderNote}.`,
        warnings,
      };
    } catch (installError: any) {
      // Automatic rollback — the switch error is the one worth reporting;
      // a rollback failure must not replace it or skip the terminal frame.
      installError.warnings = warnings;
      p({ label: "Version switch failed — rolling back safely" });
      if (installId) endProgress(installId, "error", installError.message || "Version switch failed");
      try {
        await restoreSnapshot(snapshot.id);
        await discardSnapshot(snapshot.id);
      } catch (rollbackErr: any) {
        console.error(`[VersionUpgrade ${serverId}] rollback failed:`, rollbackErr);
      }
      throw installError;
    }
  } catch (error: any) {
    // Snapshot failures land here without a terminal frame — end the
    // session so the UI doesn't freeze on the current stage forever.
    // (Inner install failures already ended it; a second terminal frame
    // is a benign overwrite during the session's grace window.)
    if (installId) endProgress(installId, "error", error.message || "Version switch failed");
    throw error;
  }
}
