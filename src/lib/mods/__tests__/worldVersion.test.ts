import { describe, it, expect, beforeEach, afterEach } from "vitest";
import fs from "fs";
import os from "os";
import path from "path";
import zlib from "zlib";
import { levelNameFor, readLevelDataVersion, stashWorldForMcSwitch } from "../worldVersion";

let root: string;

beforeEach(() => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), "worldstash-"));
});

afterEach(() => {
  fs.rmSync(root, { recursive: true, force: true });
});

/**
 * A minimal gzipped NBT level.dat: root compound > Data compound >
 * DataVersion TAG_Int, with a decoy sibling tag to prove the scanner
 * matches the real named int, not just any bytes.
 */
function writeLevelDat(serverRoot: string, levelName: string, dataVersion: number | null): void {
  const dir = path.join(serverRoot, levelName);
  fs.mkdirSync(dir, { recursive: true });
  if (dataVersion === null) {
    fs.writeFileSync(path.join(dir, "level.dat"), Buffer.from("not gzip at all"));
    return;
  }
  const name = (s: string) => {
    const b = Buffer.from(s, "latin1");
    const len = Buffer.alloc(2);
    len.writeUInt16BE(b.length);
    return Buffer.concat([len, b]);
  };
  const int32 = (n: number) => {
    const b = Buffer.alloc(4);
    b.writeInt32BE(n);
    return b;
  };
  const nbt = Buffer.concat([
    Buffer.from([0x0a]), name(""), // root compound
    Buffer.from([0x0a]), name("Data"), // Data compound
    Buffer.from([0x08]), name("Version"), name("26.2"), // decoy TAG_String
    Buffer.from([0x03]), name("DataVersion"), int32(dataVersion),
    Buffer.from([0x00]), // end Data
    Buffer.from([0x00]), // end root
  ]);
  fs.writeFileSync(path.join(dir, "level.dat"), zlib.gzipSync(nbt));
}

describe("readLevelDataVersion", () => {
  it("reads the DataVersion int from a gzipped level.dat", () => {
    writeLevelDat(root, "world", 4700);
    expect(readLevelDataVersion(root, "world")).toEqual({ exists: true, dataVersion: 4700 });
  });

  it("reports a missing world as not existing", () => {
    expect(readLevelDataVersion(root, "world")).toEqual({ exists: false, dataVersion: null });
  });

  it("reports an unparseable level.dat as existing but unreadable", () => {
    writeLevelDat(root, "world", null);
    expect(readLevelDataVersion(root, "world")).toEqual({ exists: true, dataVersion: null });
  });
});

describe("levelNameFor", () => {
  it("uses server.properties' level-name when present", () => {
    fs.writeFileSync(path.join(root, "server.properties"), "level-name=atm10\nmotd=hi\n");
    expect(levelNameFor(root)).toBe("atm10");
  });

  it("falls back to world without server.properties", () => {
    expect(levelNameFor(root)).toBe("world");
  });
});

describe("stashWorldForMcSwitch", () => {
  it("moves a world generated by a newer release aside (downgrade)", () => {
    writeLevelDat(root, "world", 4700);
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "1.21.1", targetDataVersion: 3955 });
    expect(stash.movedTo).toBeTruthy();
    expect(fs.existsSync(path.join(root, "world"))).toBe(false);
    expect(fs.existsSync(stash.movedTo!)).toBe(true);
  });

  it("keeps the world on an upgrade", () => {
    writeLevelDat(root, "world", 3955);
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "26.2", targetDataVersion: 4700 });
    expect(stash.movedTo).toBeUndefined();
    expect(fs.existsSync(path.join(root, "world"))).toBe(true);
  });

  it("moves a world whose level.dat can't be parsed (fail-safe)", () => {
    writeLevelDat(root, "world", null);
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "1.21.1", targetDataVersion: 3955 });
    expect(stash.movedTo).toBeTruthy();
    expect(fs.existsSync(path.join(root, "world"))).toBe(false);
  });

  it("moves the world when the target's DataVersion is unknown", () => {
    writeLevelDat(root, "world", 3955);
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "1.12.2", targetDataVersion: null });
    expect(stash.movedTo).toBeTruthy();
  });

  it("does nothing without a world", () => {
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "1.21.1", targetDataVersion: 3955 });
    expect(stash.movedTo).toBeUndefined();
  });

  it("stashes the level-name from server.properties, not hard-coded world", () => {
    fs.writeFileSync(path.join(root, "server.properties"), "level-name=atm10\n");
    writeLevelDat(root, "atm10", 4700);
    const stash = stashWorldForMcSwitch({ serverRoot: root, to: "1.21.1", targetDataVersion: 3955 });
    expect(stash.movedTo).toBeTruthy();
    expect(path.basename(stash.movedTo!)).toMatch(/^atm10\.pre-mc-1\.21\.1-/);
    expect(fs.existsSync(path.join(root, "atm10"))).toBe(false);
  });
});
